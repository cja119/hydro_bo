"""Report how many Sobol rows each problem has on disk, and (optionally) write a COMPACT gaps
array for only the missing rows - so a straggler resubmit queues just the rows that are actually
missing, not all 768 with skip-if-done exiting most of them.

Pure stdlib + yaml: no hydro_bo / jax / gurobi import, just file-existence checks, so it is safe
and instant to run on the login node.

    python scripts/archetype_sobol_check.py                       # report counts + missing rows
    python scripts/archetype_sobol_check.py --write-pbs           # also write a gaps pbs (3 h) for the missing rows
    python scripts/archetype_sobol_check.py --write-pbs --walltime 04:00:00
"""

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "scripts" / "config_archetypes.yml"
GAPS_PBS = ROOT / "scripts" / "pbs" / "archetype_sobol_gaps.pbs"


def problem_keys(cfg: dict) -> list[str]:
    """Problem order = archetypes x vectors, exactly as scenarios.load_problems builds it."""
    archetypes = cfg.get("problem_archetypes") or ["low", "medium", "high"]
    vectors = cfg.get("vectors") or ["NH3", "LH2"]
    return [f"{a}-{v}" for a in archetypes for v in vectors]


def missing_global_indices(cfg: dict) -> tuple[list[int], list[tuple[str, int, int]]]:
    """Global indices with no row_<row>.json on disk, and a per-problem (key, present, total) summary."""
    n = int(cfg["sobol"]["n_per_problem"])
    out_dir = ROOT / cfg["sobol"]["out_dir"]
    keys = problem_keys(cfg)
    missing, summary = [], []
    for i, key in enumerate(keys):
        present = 0
        for row in range(n):
            if (out_dir / key / f"row_{row:04d}.json").exists():
                present += 1
            else:
                missing.append(i * n + row)
        summary.append((key, present, n))
    return missing, summary


def write_gaps_pbs(missing: list[int], walltime: str) -> None:
    gaps = " ".join(str(g) for g in missing)
    text = f"""#!/bin/bash
# AUTO-GENERATED by scripts/archetype_sobol_check.py - the Sobol rows still missing on disk.
# A compact array (just the {len(missing)} missing rows), so the queue holds only real work,
# not 768 elements with skip-if-done exiting most. Re-generate after each pass.
#   qsub scripts/pbs/archetype_sobol_gaps.pbs        (from the repo root)
#PBS -N arch_sobol_gaps
#PBS -J 0-{len(missing) - 1}
#PBS -l select=ncpus=16:mem=8gb
#PBS -l walltime={walltime}
set -euo pipefail
source "$PBS_O_WORKDIR/scripts/pbs/env.sh"

# Global indices still missing; length MUST match #PBS -J ({len(missing)} -> -J 0-{len(missing) - 1}).
GAPS=({gaps})
IDX="${{GAPS[$PBS_ARRAY_INDEX]}}"

# NCPUS from this job's own select line (PBS injects NCPUS=1); see env.sh.
export NCPUS="$(awk -F'[ =:]+' '/^#PBS -l select=/{{for(i=1;i<=NF;i++) if($i=="ncpus"){{print $(i+1); exit}}}}' "$PBS_O_WORKDIR/scripts/pbs/archetype_sobol_gaps.pbs")"

LOGDIR="$PBS_O_WORKDIR/scripts/tmp/archetype_sobol/logs"
mkdir -p "$LOGDIR"
"$CONDA_PREFIX/bin/python" -u scripts/archetype_sobol.py --index "$IDX" --ncpus "$NCPUS" 2>&1 \\
    | tee "$LOGDIR/task_${{IDX}}.log"
"""
    GAPS_PBS.write_text(text)


def main():
    a = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    a.add_argument("--write-pbs", action="store_true", help="write scripts/pbs/archetype_sobol_gaps.pbs for the missing rows")
    a.add_argument("--walltime", default="03:00:00", help="walltime for the generated gaps pbs (default 03:00:00)")
    args = a.parse_args()
    cfg = yaml.safe_load(CONFIG.read_text())

    missing, summary = missing_global_indices(cfg)
    for key, present, total in summary:
        flag = "" if present == total else f"   <-- {total - present} MISSING"
        print(f"  {key:<12} {present:3d}/{total}{flag}")
    print(f"total missing: {len(missing)}")

    if not missing:
        print("all rows present - nothing to resubmit.")
        return
    print("missing global indices:", " ".join(str(g) for g in missing))
    if args.write_pbs:
        write_gaps_pbs(missing, args.walltime)
        print(f"wrote {GAPS_PBS.relative_to(ROOT)}  (-J 0-{len(missing) - 1}, walltime {args.walltime})")
        print(f"  qsub {GAPS_PBS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
